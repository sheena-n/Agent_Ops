-- =====================================================================
-- AgentOps Demo | 01 - Setup (role, warehouse, database, schemas)
-- Run as ACCOUNTADMIN (or a role with CREATE ROLE / DATABASE / WAREHOUSE)
-- =====================================================================
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AGENTOPS_DEMO_ROLE COMMENT = 'AgentOps demo owner role';
GRANT ROLE AGENTOPS_DEMO_ROLE TO ROLE SYSADMIN;
SET my_user = CURRENT_USER();
GRANT ROLE AGENTOPS_DEMO_ROLE TO USER IDENTIFIER($my_user);

-- Consumer role used later to show deployment / access
CREATE ROLE IF NOT EXISTS AGENTOPS_CONSUMER_ROLE COMMENT = 'Business users of the deployed agent';
GRANT ROLE AGENTOPS_CONSUMER_ROLE TO USER IDENTIFIER($my_user);

CREATE WAREHOUSE IF NOT EXISTS AGENTOPS_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE AGENTOPS_WH TO ROLE AGENTOPS_DEMO_ROLE;
GRANT USAGE ON WAREHOUSE AGENTOPS_WH TO ROLE AGENTOPS_CONSUMER_ROLE;

GRANT CREATE DATABASE ON ACCOUNT TO ROLE AGENTOPS_DEMO_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENTOPS_DEMO_ROLE;
-- Evaluations (SV + agent) run as background tasks
GRANT EXECUTE TASK ON ACCOUNT TO ROLE AGENTOPS_DEMO_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENTOPS_CONSUMER_ROLE;

USE ROLE AGENTOPS_DEMO_ROLE;
USE WAREHOUSE AGENTOPS_WH;

CREATE DATABASE IF NOT EXISTS AGENTOPS_DB COMMENT = 'Telecom AgentOps demo';
-- Single schema for everything: data, semantic view, agent, EVAL_* and OPS_* tables
CREATE SCHEMA IF NOT EXISTS AGENTOPS_DB.TELCO COMMENT = 'Telecom AgentOps demo: data, semantic view, agent, evals, ops';
CREATE SCHEMA IF NOT EXISTS AGENTOPS_DB.SEMANTIC_VIEWS_DEV COMMENT = 'Dev semantic views (deploy target Dev; promote to TELCO for prod)';

-- Consumer access (read through the agent only)
GRANT USAGE ON DATABASE AGENTOPS_DB TO ROLE AGENTOPS_CONSUMER_ROLE;
GRANT USAGE ON SCHEMA AGENTOPS_DB.TELCO TO ROLE AGENTOPS_CONSUMER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AGENTOPS_DB.TELCO TO ROLE AGENTOPS_CONSUMER_ROLE;



